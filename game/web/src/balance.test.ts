import assert from 'node:assert/strict';
import {world,status,until,delay} from './test-world';
const w=await world();const {db,game,own,build,lord}=w;
const stock=()=>db.db.playerResources.connectionId.find(db.connectionId)!;
const nodes=()=>Array.from(db.db.resourceNode.iter()).filter(n=>n.gameId===game);
const call=(name:'onSetTargets'|'onMoveToRoof'|'onUnassignPeasant'|'onRemoveBuilding',action:()=>void)=>status(db,c=>db.reducers[name](c as never),action);
try {
 assert.deepEqual([stock().wood,stock().stone,stock().iron],[120,120,120]);
 const stone=nodes().filter(n=>n.kind===1);assert.ok(stone.every(n=>n.capacity>10000));assert.ok(new Set(stone.map(n=>n.capacity)).size>1);
 assert.ok(nodes().filter(n=>n.kind===0).every(n=>n.capacity===24));
 assert.equal((await build('stockpile',-9,-43)).tag,'Committed');
 assert.equal((await build('saw_pit',40,-43)).tag,'Committed');
 assert.equal((await build('quarry',-65,-35)).tag,'Committed');
 const quarry=own().find(b=>b.kind==='quarry')!;
 await until(()=>db.db.producer.buildingId.find(quarry.id)!.buffer>=2,'quarry starts working without manual cart assignment',65000);
 assert.ok(Array.from(db.db.worker.iter()).filter(w=>w.sourceBuilding===quarry.id).every(w=>w.cargo===0));
 const stoneBeforeCart=stock().stone;
 assert.equal((await build('ox_tether',-55,-35)).tag,'Committed','cart may be built inside stone field');
 const cart=own().find(b=>b.kind==='ox_tether')!;
 await until(()=>db.db.oxCart.buildingId.find(cart.id)?.sourceBuilding===quarry.id,'nearby cart automatically chooses quarry',15000);
 await until(()=>nodes().some(n=>n.kind===0&&n.phase===2&&n.remaining>0),'first tree falls after worker reaches forest',90000);
 const chopped=nodes().find(n=>n.kind===0&&n.phase===2&&n.remaining>0)!;
 assert.ok(chopped,'tree really fell');const before=chopped.remaining;await delay(14000);
 const after=db.db.resourceNode.id.find(chopped.id)!;assert.ok(after.remaining>0&&before-after.remaining<=3,'one tree remains for minutes, not seconds');
 const keep=own().find(b=>b.kind==='keep')!;
 assert.equal((await call('onSetTargets',()=>db.reducers.setTargets([lord().id],keep.x-18,keep.z+16))).tag,'Committed');
 await until(()=>!db.db.towerOccupant.unitId.find(lord().id),'lord descends original east staircase',25000);
 await until(()=>Math.hypot(lord().x-(keep.x-18),lord().z-(keep.z+16))<1,'lord approaches left staircase',20000);
 assert.equal((await call('onMoveToRoof',()=>db.reducers.moveToRoof([lord().id],keep.id,keep.x-3,keep.z))).tag,'Committed');
 await until(()=>lord().x<keep.x-6&&lord().y>1&&lord().y<5,'unit physically climbs west staircase',20000);
 await until(()=>Math.abs(lord().y-6.15)<.02,'unit reaches terrace from west',15000);
 assert.equal(db.db.towerOccupant.unitId.find(lord().id)!.door,1);
 assert.equal((await call('onSetTargets',()=>db.reducers.setTargets([lord().id],keep.x-14,keep.z+16))).tag,'Committed');
 await until(()=>lord().x<keep.x-6&&lord().y>1&&lord().y<5,'unit physically descends west staircase',15000);
 await until(()=>!db.db.towerOccupant.unitId.find(lord().id),'unit returns to ground',15000);
 await until(()=>stock().stone>=stoneBeforeCart+18,'automatic cart delivers an actual stone load',170000);
 await until(()=>stock().wood>=12,'wood economy funds next building',90000);
 assert.equal((await build('iron_mine',-80,15)).tag,'Committed');const mine=own().find(b=>b.kind==='iron_mine')!;
 assert.equal((await call('onUnassignPeasant',()=>db.reducers.unassignPeasant(quarry.id))).tag,'Committed');
 await until(()=>db.db.oxCart.buildingId.find(cart.id)?.sourceBuilding===mine.id,'cart automatically switches to nearby open mine',30000);
 assert.equal((await call('onRemoveBuilding',()=>db.reducers.removeBuilding(mine.id))).tag,'Committed');
 assert.ok(!own().some(b=>b.id===mine.id));assert.ok(!Array.from(db.db.worker.iter()).some(w=>w.sourceBuilding===mine.id));
 await until(()=>db.db.oxCart.buildingId.find(cart.id)?.sourceBuilding===undefined,'deleting workplace frees cart',10000);
 assert.equal((await call('onRemoveBuilding',()=>db.reducers.removeBuilding(cart.id))).tag,'Committed');
 assert.ok(!db.db.oxCart.buildingId.find(cart.id));
 console.log('PASS: 120 starting materials, large area-based deposits, slow real tree harvest, resource-field cart construction, automatic full-load delivery and reassignment, both physical palace stairs, building demolition and cleanup.');
}finally{db.disconnect()}
