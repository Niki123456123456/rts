#!/usr/bin/env python3
"""Package stockpile goods and retain canonical horizontal positions for partial layers."""
import json,struct,sys
sys.dont_write_bytecode=True
from pathlib import Path
ROOT=Path(__file__).resolve().parent
source=ROOT.parent/'assets/models/meshes/buildings/stockpile'
folder=ROOT/'assets/models/resources';folder.mkdir(parents=True,exist_ok=True)
names=['wood_1','stone_layer_1']+[f'stone_{i}' for i in range(1,9)]+['iron_layer_1']+[f'iron_{i}' for i in range(1,12)]
definitions=[]
food_sources=[('food_apples','meshes/buildings/apples_01'),('food_bread','meshes/buildings/bread_01'),('food_cheese','meshes/buildings/cheese_01'),('food_meat','meshes/units/models/goods_meat')]
entries=[(name,source/(name+'.glb')) for name in names]+[(name,ROOT.parent/'assets/models'/(path+'.glb')) for name,path in food_sources]
for name,path in entries:
    raw=path.read_bytes();n=struct.unpack_from('<I',raw,12)[0];doc=json.loads(raw[20:20+n]);tail=raw[20+n:]
    for material in doc.get('materials',[]):material['alphaMode']='OPAQUE'
    pos=[doc['accessors'][p['attributes']['POSITION']] for m in doc['meshes'] for p in m['primitives']]
    lo=[min(p['min'][i] for p in pos) for i in range(3)];hi=[max(p['max'][i] for p in pos) for i in range(3)]
    encoded=json.dumps(doc,separators=(',',':')).encode();encoded+=b' '*(-len(encoded)%4)
    (folder/(name+'.glb')).write_bytes(struct.pack('<III',0x46546c67,2,20+len(encoded)+len(tail))+struct.pack('<II',len(encoded),0x4e4f534a)+encoded+tail)
    definitions.append(f'    StorageModel {{ path: "models/resources/{name}.glb#Scene0", base: {float(lo[1])}, center: [{(lo[0]+hi[0])/2}, {(lo[2]+hi[2])/2}], height: {float(hi[1]-lo[1])} }},')
(ROOT/'src/storage_models.rs').write_text('// Generated by game/import-storage.py. Source coordinates are centimetres.\npub struct StorageModel {pub path: &\'static str,pub base:f32,pub center:[f32;2],pub height:f32}\npub const MODELS:[StorageModel;26]=[\n'+'\n'.join(definitions)+'\n];\n')
