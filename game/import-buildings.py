#!/usr/bin/env python3
"""Package catalog models, collision meshes and shared bounds from the source archive.

Run only when importing models. CI builds the committed GLBs and generated catalog
without the source archive. Closed buildings use OPAQUE materials because the
exported DDS alpha channels contain surface data rather than transparency.
Models without supplied collision geometry receive a conservative bounding box.
"""
import sys
sys.dont_write_bytecode = True
import json
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / 'assets/models/meshes/buildings'
DESTINATION = ROOT / 'assets/models/buildings'


def unpack(data):
    length, _ = struct.unpack_from('<II', data, 12)
    return json.loads(data[20:20 + length]), data[20 + length:]


def pack(document, tail):
    encoded = json.dumps(document, separators=(',', ':')).encode()
    encoded += b' ' * (-len(encoded) % 4)
    return (struct.pack('<III', 0x46546c67, 2, 20 + len(encoded) + len(tail))
            + struct.pack('<II', len(encoded), 0x4e4f534a) + encoded + tail)


def bounds(document):
    positions = [document['accessors'][p['attributes']['POSITION']]
                 for mesh in document['meshes'] for p in mesh['primitives']]
    return ([min(a['min'][i] for a in positions) for i in range(3)],
            [max(a['max'][i] for a in positions) for i in range(3)])


def box_collision(minimum, maximum):
    points = [(x, y, z) for x in [minimum[0], maximum[0]]
              for y in [minimum[1], maximum[1]] for z in [minimum[2], maximum[2]]]
    indices = [0, 1, 3, 0, 3, 2, 4, 6, 7, 4, 7, 5,
               0, 4, 5, 0, 5, 1, 2, 3, 7, 2, 7, 6,
               0, 2, 6, 0, 6, 4, 1, 5, 7, 1, 7, 3]
    binary = b''.join(struct.pack('<fff', *p) for p in points) + struct.pack('<36H', *indices)
    document = {
        'asset': {'version': '2.0', 'generator': 'Stronghold bounding-box collision'},
        'scene': 0, 'scenes': [{'nodes': [0]}], 'nodes': [{'mesh': 0}],
        'meshes': [{'primitives': [{'attributes': {'POSITION': 0}, 'indices': 1}]}],
        'buffers': [{'byteLength': len(binary)}],
        'bufferViews': [{'buffer': 0, 'byteOffset': 0, 'byteLength': 96, 'target': 34962},
                        {'buffer': 0, 'byteOffset': 96, 'byteLength': 72, 'target': 34963}],
        'accessors': [{'bufferView': 0, 'componentType': 5126, 'count': 8, 'type': 'VEC3',
                       'min': minimum, 'max': maximum},
                      {'bufferView': 1, 'componentType': 5123, 'count': 36, 'type': 'SCALAR'}],
    }
    return pack(document, struct.pack('<II', len(binary), 0x004e4942) + binary)


def main():
    catalog = json.loads((ROOT / 'building-models.json').read_text())
    definitions = []
    for item in catalog:
        if len(item['grid']) != 2 or any(type(n) is not int or not 1 <= n <= 400 for n in item['grid']):
            raise ValueError(f"Invalid grid size for {item['id']}")
        relative = f"models/buildings/{item['category']}/{item['folder']}"
        folder = ROOT / 'assets' / relative
        folder.mkdir(parents=True, exist_ok=True)
        if item.get('procedural') == 'stone_wall':
            import importlib.util
            spec = importlib.util.spec_from_file_location('stone_wall', ROOT / 'create-stone-wall.py')
            generator = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(generator)
            minimum, maximum = generator.generate()
        else:
            visual, tail = unpack((SOURCE / (item['source'] + '.glb')).read_bytes())
            for material in visual.get('materials', []):
                material['alphaMode'] = 'OPAQUE'
            if item['collision']:
                collision = (SOURCE / (item['collision'] + '.glb')).read_bytes()
                minimum, maximum = bounds(unpack(collision)[0])
            else:
                minimum, maximum = bounds(visual)
                collision = box_collision(minimum, maximum)
            (folder / 'mesh.glb').write_bytes(pack(visual, tail))
            (folder / 'collision.glb').write_bytes(collision)
        definitions.append('    Definition { name: %s, label: %s, category: %s, scene: %s, collision: %s, min: %s, max: %s, grid: %s },' % (
            json.dumps(item['id']), json.dumps(item['label'], ensure_ascii=False), json.dumps(item['category']),
            json.dumps(relative + '/mesh.glb#Scene0'), json.dumps(relative + '/collision.glb#Mesh0/Primitive0'),
            repr([float(x) for x in minimum]), repr([float(x) for x in maximum]), repr(item['grid'])))
    variants = ',\n    '.join(item['variant'] for item in catalog)
    all_kinds = ', '.join('Self::' + item['variant'] for item in catalog)
    output = '''// Generated by game/import-buildings.py from game/building-models.json.
use crate::{Obstacle, Point, MODEL_SCALE};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[repr(usize)]
pub enum BuildingKind {
    #[default]
    %s,
}
struct Definition {
    name: &'static str,
    label: &'static str,
    category: &'static str,
    scene: &'static str,
    collision: &'static str,
    min: [f32; 3],
    max: [f32; 3],
    grid: [u16; 2],
}
const DEFINITIONS: [Definition; %d] = [
%s
];
impl BuildingKind {
    pub const ALL: [Self; %d] = [%s];
    pub fn index(self) -> usize { self as usize }
    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|kind| kind.name() == name)
    }
    pub fn name(self) -> &'static str { DEFINITIONS[self.index()].name }
    pub fn label(self) -> &'static str { DEFINITIONS[self.index()].label }
    pub fn category(self) -> &'static str { DEFINITIONS[self.index()].category }
    pub fn scene(self) -> &'static str { DEFINITIONS[self.index()].scene }
    pub fn collision(self) -> &'static str { DEFINITIONS[self.index()].collision }
    pub fn grid_size(self) -> (u16, u16) {
        let [width, depth] = DEFINITIONS[self.index()].grid;
        (width, depth)
    }
    pub fn center(self) -> Point {
        let d = &DEFINITIONS[self.index()];
        ((d.min[0] + d.max[0]) * 0.5, (d.min[2] + d.max[2]) * 0.5)
    }
    pub fn height(self) -> f32 { let d = &DEFINITIONS[self.index()]; (d.max[1] - d.min[1]) * MODEL_SCALE }
    pub fn ground_offset(self) -> f32 { -DEFINITIONS[self.index()].min[1] * MODEL_SCALE }
    pub fn obstacle(self, x: f32, z: f32) -> Obstacle {
        let d = &DEFINITIONS[self.index()];
        Obstacle { x, z, half_x: (d.max[0] - d.min[0]) * MODEL_SCALE * 0.5,
            half_z: (d.max[2] - d.min[2]) * MODEL_SCALE * 0.5 }
    }
}
''' % (variants, len(catalog), '\n'.join(definitions), len(catalog), all_kinds)
    generated = ROOT.parent / 'shared/src/building_catalog.rs'
    generated.write_text(output)
    subprocess.run(['rustfmt', '--edition', '2021', str(generated)], check=True)


if __name__ == '__main__':
    main()
